import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';

const origin = process.env.SANITY_TEST_URL || 'http://localhost:3011';
const secret = 'local-sanity-test-secret';
async function page(path, status = 200) {
  const response = await fetch(origin + path);
  assert.equal(response.status, status, `${path} status`);
  return response.text();
}
const about = await page('/about');
assert.match(about, /<title>CMS about title override<\/title>/);
assert.match(about, /name="description" content="CMS about description override"/);
assert.match(about, /rel="canonical" href="https:\/\/www\.truedgedigital\.co\.uk\/about"/);
assert.match(about, /name="robots" content="noindex, follow"/);
assert.match(about, /CMS controlled heading/);
assert.match(about, /CMS controlled introduction/);
assert.match(about, /"@type":"FAQPage"/);
assert.match(about, /Does CMS FAQ publishing work\?/);
const works = await page('/works');
assert.match(works, /<title>Our Work \| Truedge Digital<\/title>/, 'Missing CMS page retains fallback metadata');
const contact = await page('/contact?project=walker');
assert.match(contact, /<h1[^>]*id="contact-title"/, 'Contact heading is server-rendered');
const customJson = contact.match(/<script type="application\/ld\+json">(.*?)<\/script>/)?.[1];
assert(customJson?.includes('\\u003c/script>'), 'Custom JSON-LD escapes HTML closing tags');
assert.equal(JSON.parse(customJson).name, '</script><script>should never execute</script>');
const blog = await page('/blog');
assert.match(blog, /href="\/blog\/sanity-integration-test"/);
const article = await page('/blog/sanity-integration-test');
assert.match(article, /<title>CMS article title override<\/title>/);
assert.match(article, /<h2>Semantic article heading<\/h2>/);
assert.match(article, /rel="noopener noreferrer nofollow"/);
assert.doesNotMatch(article, /href="javascript:/);
assert.match(article, /<ul>/);
assert.match(article, /alt="A test image with descriptive alternative text"/);
assert.match(article, /"@type":"BlogPosting"/);
assert.equal((article.match(/<h1(?:\s|>)/g) || []).length, 1, 'Exactly one H1 per article');
await page('/blog/does-not-exist', 404);
const sitemap = await page('/sitemap.xml');
assert.doesNotMatch(sitemap, /<loc>https:\/\/www\.truedgedigital\.co\.uk\/about<\/loc>/, 'noIndex core route excluded');
assert.doesNotMatch(sitemap, /sanity-integration-test/, 'noIndex post excluded');
const unsigned = await fetch(origin + '/api/revalidate', { method: 'POST', body: '{}' });
assert.equal(unsigned.status, 401, 'Unsigned webhook rejected');
const body = JSON.stringify({ _type: 'blogPost' });
const timestamp = Date.now().toString();
const signature = createHmac('sha256', secret).update(`${timestamp}.${body}`).digest('base64url');
const valid = await fetch(origin + '/api/revalidate', { method: 'POST', headers: { 'content-type': 'application/json', 'sanity-webhook-signature': `t=${timestamp},v1=${signature}` }, body });
assert.equal(valid.status, 200, 'Signed webhook accepted');
console.log('PASS: CMS metadata, hero overrides, FAQ JSON-LD, metadata fallback, blog rendering, safe links, images, single H1, 404s, noindex sitemap exclusions, and signed webhook authentication.');
